use crate::models::messages::{ChatBatch, StreamEvent, StreamMessage};
use shine_infra::session::SessionKey;
use uuid::Uuid;

/// High level filter for messages sent to the hub bus.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum TopicKey {
    Hub,
    Chat,
    /// Command stream subscription events; internal subscribers only.
    Stream,
}

pub trait ToTopic {
    fn topic(&self) -> TopicKey;
}

/// Why a connection ended.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum DisconnectReason {
    /// The client went away; not a drop.
    Client,
    /// The same user connected again.
    Replaced,
    /// Another instance took the user over.
    RegistryInactive,
    /// The registry row expired or was replaced, found by the heartbeat.
    HeartbeatInactive,
    /// The session expired or was compromised.
    SessionInvalid,
    /// The egress channel was full.
    SlowConsumer,
    /// The egress channel was closed without a disconnect.
    DeadChannel,
    /// The hub is shutting down.
    Shutdown,
}

impl DisconnectReason {
    /// Stable name used for metric labels, logs and the ws close reason.
    pub fn as_str(self) -> &'static str {
        match self {
            DisconnectReason::Client => "client",
            DisconnectReason::Replaced => "replaced",
            DisconnectReason::RegistryInactive => "registry_inactive",
            DisconnectReason::HeartbeatInactive => "heartbeat_inactive",
            DisconnectReason::SessionInvalid => "session_invalid",
            DisconnectReason::SlowConsumer => "slow_consumer",
            DisconnectReason::DeadChannel => "dead_channel",
            DisconnectReason::Shutdown => "shutdown",
        }
    }

    /// Whether the hub removed the connection, as opposed to the client leaving.
    pub fn is_drop(self) -> bool {
        self != DisconnectReason::Client
    }
}

impl std::fmt::Display for DisconnectReason {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}

/// A lifecycle event generated by the hub itself.
#[derive(Clone, Debug)]
pub enum HubEvent {
    UserConnected {
        user_id: Uuid,
        connection_id: Uuid,
        session_key: SessionKey,
    },
    UserDisconnected {
        user_id: Uuid,
        connection_id: Uuid,
        reason: DisconnectReason,
    },
    Shutdown,
}

impl ToTopic for HubEvent {
    fn topic(&self) -> TopicKey {
        TopicKey::Hub
    }
}

/// A message carried on the hub bus: a hub lifecycle event or a domain payload.
#[derive(Clone, Debug)]
pub enum HubMessage {
    Hub(HubEvent),
    Chat(ChatBatch),
    /// Command stream egress to one connection.
    Stream(StreamMessage),
    /// Command stream subscription change, for internal subscribers.
    StreamEvent(StreamEvent),
}

impl ToTopic for HubMessage {
    fn topic(&self) -> TopicKey {
        match self {
            HubMessage::Hub(event) => event.topic(),
            HubMessage::Chat(batch) => batch.topic(),
            HubMessage::Stream(_) => TopicKey::Stream,
            HubMessage::StreamEvent(event) => event.topic(),
        }
    }
}
